def load_trials(source: Path):
    with open(source, encoding="utf-8") as f:
        data = json.load(f)
    trials = []
    seen = set()
    for t in data.get("trials", []):
        nct = clean(t.get("nct_id"))
        if not nct or nct in seen:
            continue
        seen.add(nct)
        t = dict(t)
        t["nct_id"] = nct
        t["status"] = clean(t.get("status")).upper() or "UNKNOWN"
        t["url"] = clean(t.get("link")) or f"https://clinicaltrials.gov/study/{nct}"
        t["agents"] = [clean(a) for a in (t.get("agents") or []) if clean(a)]
        t["mapped_conditions"] = [clean(c) for c in (t.get("mapped_conditions") or []) if clean(c)]
        t["conditions_raw"] = [clean(c) for c in (t.get("conditions_raw") or []) if clean(c)]
        t["summary"] = summarise(t.get("brief_summary"))
        trials.append(t)
    trials.sort(key=_recency, reverse=True)
    return data.get("last_run") or datetime.utcnow().isoformat(), trials


def write(path: Path, content: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old != content:
        path.write_text(content, encoding="utf-8", newline="\n")
        return True
    return False


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", type=Path, default=DEFAULT_SOURCE, help="path to clinical_trials_current.json")
    ap.add_argument("--min-agent-trials", type=int, default=2)
    args = ap.parse_args(argv)

    if not args.source.exists():
        print(f"ERROR: source not found: {args.source}", file=sys.stderr)
        return 1
    last_run, trials = load_trials(args.source)
    print(f"source: {args.source} ({len(trials)} trials, last_run {last_run})")

    # agents with >= N trials (excluding comparator noise)
    agent_trials = defaultdict(list)
    for t in trials:
        for a in sorted(set(t["agents"])):
            if NOISE_AGENT_RE.search(a):
                continue
            agent_trials[a].append(t)
    n_total_agents = len(agent_trials)
    eligible = {a: ts for a, ts in agent_trials.items() if len(ts) >= args.min_agent_trials}
    # resolve slug collisions deterministically
    slug_of, used = {}, {}
    for a in sorted(eligible, key=lambda s: (-len(eligible[s]), s.lower())):
        s = slugify(a)
        if s in used:
            i = 2
            while f"{s}-{i}" in used:
                i += 1
            s = f"{s}-{i}"
        used[s] = a
        slug_of[a] = s

    written = changed = 0

    def emit(path, content):
        nonlocal written, changed
        written += 1
        if write(path, content):
            changed += 1

    stats = {}
    for slug, cfg in CONDITIONS.items():
        html_out, n_open = build_recruiting_page(slug, cfg, trials, last_run, slug_of)
        emit(OUT_DIR / f"{slug}-recruiting.html", html_out)
        html_out, n_all = build_all_page(slug, cfg, trials, last_run, slug_of)
        emit(OUT_DIR / f"all-{slug}.html", html_out)
        stats[slug] = {"open": n_open, "all": n_all}
        print(f"  {cfg['name']}: {n_open} open / {n_all} total")

    agent_rows = []
    for a in sorted(eligible, key=lambda s: slug_of[s]):
        ts = eligible[a]
        aslug = slug_of[a]
        emit(AGENT_DIR / f"{aslug}.html", build_agent_page(a, aslug, ts, last_run, slug_of))
        agent_rows.append({"agent": a, "slug": aslug, "n": len(ts), "open": sum(1 for t in ts if t["status"] in OPEN_STATUSES)})
    emit(AGENT_DIR / "index.html", build_agent_index(agent_rows, last_run, n_total_agents))
    print(f"  by-agent: {len(agent_rows)} agents with >= {args.min_agent_trials} trials (of {n_total_agents} distinct non-comparator agents)")

    emit(OUT_DIR / "index.html", build_hub(stats, agent_rows, last_run, trials))

    # remove stale generated agent pages
    keep = {f"{s}.html" for s in slug_of.values()} | {"index.html"}
    removed = 0
    if AGENT_DIR.exists():
        for p in AGENT_DIR.glob("*.html"):
            if p.name not in keep:
                try:
                    if MARKER in p.read_text(encoding="utf-8", errors="ignore"):
                        p.unlink()
                        removed += 1
                except OSError:
                    pass
    print(f"done: {written} pages generated, {changed} changed, {removed} stale by-agent pages removed -> {OUT_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
