def trial_ld(t, condition_name=None):
    d = {
        "@type": "MedicalTrial",
        "name": clean(t.get("title")) or t["nct_id"],
        "url": t["url"],
        "identifier": t["nct_id"],
        "status": SCHEMA_STATUS.get(t["status"], t["status"].replace("_", " ").title()),
        "phase": phase_label(t.get("phase")),
    }
    if clean(t.get("sponsor")):
        d["sponsor"] = {"@type": "Organization", "name": clean(t["sponsor"])}
    conds = t.get("conditions_raw") or ([condition_name] if condition_name else [])
    if conds:
        d["healthCondition"] = [{"@type": "MedicalCondition", "name": c} for c in conds[:5]]
    return d


