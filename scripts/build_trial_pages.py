def card(t, show_conditions=False, agent_links=None):
    st = t["status"]
    cls = STATUS_CLASS.get(st, "unknown")
    agents = t["agents"]
    if agent_links:
        agent_html = ", ".join(
            f'<a href="/trials/by-agent/{agent_links[a]}.html">{esc(a)}</a>' if a in agent_links else esc(a)
            for a in agents
        )
    else:
        agent_html = esc(", ".join(agents))
    meta = []
    meta.append(f'<span class="badge badge-{cls}">{esc(status_label(st))}</span><span class="badge badge-phase">{esc(phase_label(t.get("phase")))}</span> <a href="{esc(t["url"])}" target="_blank" rel="noopener">{esc(t["nct_id"])}</a>')
    sponsor = clean(t.get("sponsor"))
    stype = sponsor_type_label(t.get("sponsor_type"))
    if sponsor:
        meta.append(f"<strong>Sponsor:</strong> {esc(sponsor)}" + (f" ({esc(stype)})" if stype else ""))
    if agents:
        meta.append(f"<strong>Intervention(s):</strong> {agent_html}")
    if show_conditions:
        mc = ", ".join(t["mapped_conditions"])
        if mc:
            meta.append(f"<strong>Condition group:</strong> {esc(mc)}")
    dates = []
    if fmt_date(t.get("start_date")):
        dates.append(f"<strong>Start:</strong> {esc(fmt_date(t['start_date']))}")
    if fmt_date(t.get("primary_completion_date")):
        dates.append(f"<strong>Primary completion:</strong> {esc(fmt_date(t['primary_completion_date']))}")
    enr = t.get("enrollment")
    if isinstance(enr, (int, float)) and enr > 0:
        et = clean(t.get("enrollment_type")).lower()
        dates.append(f"<strong>Enrollment:</strong> {int(enr)}" + (f" ({et})" if et else ""))
    if dates:
        meta.append(" &nbsp;|&nbsp; ".join(dates))
    if fmt_date(t.get("last_updated")):
        meta.append(f"<strong>Record last updated:</strong> {esc(fmt_date(t['last_updated']))}")
    summary = t["summary"]
    summary_html = f'<p class="trial-summary">{esc(summary)}</p>' if summary else ""
    meta_html = "\n  ".join(f'<div class="trial-meta">{m}</div>' for m in meta)
    return f"""<article class="trial-card status-{cls}" id="{esc(t['nct_id'])}">
  <div class="trial-title"><a href="{esc(t['url'])}" target="_blank" rel="noopener">{esc(clean(t.get('title')) or t['nct_id'])}</a></div>
  {meta_html}
  {summary_html}
  <a href="{esc(t['url'])}" target="_blank" rel="noopener" class="btn-trial">View on ClinicalTrials.gov ↗</a>
</article>"""


def _recency(t):
    return (clean(t.get("last_updated")), t["nct_id"])


def grouped_cards(trials, by_phase=True, show_conditions=False, agent_links=None, group_desc=None):
    """Group by status (then phase) and render."""
    out = []
    by_status = defaultdict(list)
    for t in trials:
        by_status[t["status"]].append(t)
    for st in sorted(by_status, key=status_key):
        group = by_status[st]
        out.append(f'<section class="status-group" id="status-{esc(st.lower())}"><h2>{esc(status_label(st))} <span style="color:var(--text-gray);font-weight:500;font-size:0.9rem">({len(group)})</span></h2>')
        if group_desc and st in group_desc:
            out.append(f'<p class="group-sub">{group_desc[st]}</p>')
        if by_phase:
            by_phase_map = defaultdict(list)
            for t in group:
                by_phase_map[clean(t.get("phase")) or "NA"].append(t)
            for ph in sorted(by_phase_map, key=phase_key):
                items = sorted(by_phase_map[ph], key=_recency, reverse=True)
                out.append(f'<div class="phase-group"><h3>{esc(phase_label(ph))} <span style="color:var(--text-gray);font-weight:500">({len(items)})</span></h3><div class="card-list">')
                out.extend(card(t, show_conditions, agent_links) for t in items)
                out.append("</div></div>")
        else:
            items = sorted(group, key=_recency, reverse=True)
            out.append('<div class="card-list">')
            out.extend(card(t, show_conditions, agent_links) for t in items)
            out.append("</div>")
        out.append("</section>")
    return "\n".join(out)


