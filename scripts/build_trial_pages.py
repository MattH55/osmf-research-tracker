def esc(s) -> str:
    if s is None:
        return ""
    return html.escape(str(s), quote=True)


def clean(s) -> str:
    """Return '' for None / 'None' / 'nan' / 'N/A' style values."""
    if s is None:
        return ""
    s = str(s).strip()
    if s.lower() in ("none", "nan", "null", "n/a", ""):
        return ""
    return s


def slugify(s: str) -> str:
    s = s.lower()
    s = re.sub(r"[¹²³⁰-₟]", "", s)
    s = re.sub(r"[^a-z0-9]+", "-", s)
    return s.strip("-") or "agent"


def month_year(iso: str) -> str:
    try:
        return datetime.fromisoformat(iso.replace("Z", "+00:00")).strftime("%B %Y")
    except Exception:
        return datetime.utcnow().strftime("%B %Y")


def long_date(iso: str) -> str:
    try:
        return datetime.fromisoformat(iso.replace("Z", "+00:00")).strftime("%d %B %Y")
    except Exception:
        return iso


def fmt_date(d) -> str:
    d = clean(d)
    if not d:
        return ""
    for fmt, out in (("%Y-%m-%d", "%b %Y"), ("%Y-%m", "%b %Y"), ("%Y", "%Y")):
        try:
            return datetime.strptime(d, fmt).strftime(out)
        except ValueError:
            pass
    return d


_LABEL_RE = re.compile(
    r"^\s*(background|objective|objectives|aim|aims|purpose|rationale|introduction|"
    r"design|methods|eligibility|hypothesis|summary|brief summary|study description)\s*:?\s*$",
    re.I,
)


def summarise(text, max_sent=3, max_chars=420) -> str:
    """Trim a ClinicalTrials.gov brief summary to 2-3 readable sentences."""
    text = clean(text)
    if not text:
        return ""
    # drop section labels like "Background:" on their own line
    lines = [ln.strip() for ln in text.splitlines()]
    lines = [ln for ln in lines if ln and not _LABEL_RE.match(ln)]
    text = " ".join(lines)
    text = re.sub(r"^\s*(background|objective|purpose|aims?)\s*:\s*", "", text, flags=re.I)
    text = re.sub(r"\s+", " ", text).strip()
    sents = re.split(r"(?<=[.!?])\s+(?=[A-Z0-9\"'(])", text)
    out, total = [], 0
    for s in sents:
        if not s:
            continue
        if out and (len(out) >= max_sent or total + len(s) > max_chars):
            break
        out.append(s)
        total += len(s)
    res = " ".join(out).strip()
    if len(res) > max_chars + 120:
        res = res[: max_chars + 100].rsplit(" ", 1)[0] + "…"
    if res and res[-1] not in ".!?…":
        res += "."
    return res


def phase_key(p: str) -> int:
    p = clean(p) or "NA"
    return PHASE_ORDER.index(p) if p in PHASE_ORDER else len(PHASE_ORDER)


def status_key(s: str) -> int:
    return STATUS_ORDER.index(s) if s in STATUS_ORDER else len(STATUS_ORDER)


def phase_label(p) -> str:
    p = clean(p) or "NA"
    return PHASE_LABEL.get(p, p.replace("_", " ").title())


def status_label(s) -> str:
    s = clean(s) or "UNKNOWN"
    return STATUS_LABEL.get(s, s.replace("_", " ").title())


def sponsor_type_label(s) -> str:
    s = clean(s)
    return SPONSOR_TYPE_LABEL.get(s, s.title()) if s else ""


def jsonld(obj) -> str:
    return '<script type="application/ld+json">\n' + json.dumps(obj, ensure_ascii=False, indent=1).replace("</", "<\\/") + "\n</script>"


